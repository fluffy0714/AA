// Optional browser QA: install Playwright or set PLAYWRIGHT_MODULE to its module path.
import { mkdir } from 'node:fs/promises';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
await mkdir('artifacts', { recursive: true });
import assert from 'node:assert/strict';
const browser = await chromium.launch({executablePath:process.env.BROWSER_PATH || undefined,headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:1050},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(process.env.AA_BASE_URL || 'http://127.0.0.1:3000');
await page.locator('.product').last().waitFor();
assert.equal(await page.locator('.product').count(),12);
await page.screenshot({path:'artifacts/desktop-empty.png',fullPage:true});
await page.locator('#sample-button').click();
await page.locator('.quote.winner').waitFor();
assert.match(await page.locator('.quote.winner .provider-name').textContent(),/Яндекс/);
assert.equal(await page.locator('#basket-count').textContent(),'5');
await page.locator('#promo').fill('DEMO10');await page.locator('#promo-form button').click();
await page.waitForFunction(()=>document.querySelector('.quote.winner .provider-name')?.textContent.includes('Купер'));
await page.locator('#details-button').click();
await page.locator('dialog[open]').waitFor();
assert.match(await page.locator('dialog').textContent(),/Оформление пока недоступно/);
assert.equal(await page.locator('dialog button:disabled').count(),1);
await page.screenshot({path:'artifacts/comparison.png'});
await page.keyboard.press('Escape');
await page.locator('#scenario').selectOption('missing');
await page.waitForFunction(()=>document.querySelector('#quotes')?.textContent.includes('Сравнение неполное'));
assert.equal(await page.locator('.winner-badge').count(),0);
await page.locator('#scenario').selectOption('outage');
await page.waitForFunction(()=>document.querySelector('#quotes')?.textContent.includes('Сервис не ответил'));
await page.locator('#scenario').selectOption('normal');
await page.locator('.winner-badge').waitFor();
await page.locator('#search').fill('молоко');assert.equal(await page.locator('.product').count(),1);
await page.locator('#search').fill('несуществующий товар');assert.equal(await page.locator('.no-results').count(),1);
await page.locator('#reset-search').click();assert.equal(await page.locator('.product').count(),12);
await page.screenshot({path:'artifacts/desktop.png',fullPage:true});
await page.locator('#clear-button').click();assert.equal(await page.locator('#basket-count').textContent(),'0');
assert.ok(await page.locator('#details-button').isDisabled());
await page.locator('[data-category="Молочное"]').click();assert.equal(await page.locator('.product').count(),4);
await page.locator('[data-category="Все продукты"]').click();
await page.setViewportSize({width:390,height:844});
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
await page.locator('#sample-button').click();await page.locator('.winner-badge').waitFor();
await page.evaluate(()=>scrollTo(0,0));await page.screenshot({path:'artifacts/mobile.png',fullPage:true});
await page.locator('#details-button').click();assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
await page.keyboard.press('Escape');
await page.reload();await page.locator('.product').last().waitFor();assert.equal(await page.locator('#basket-count').textContent(),'0');
assert.deepEqual(errors,[]);
console.log('Browser QA passed: 12 products, demo basket, exact totals, promo winner, detail dialog, missing item, outage, search, filters, clear, 390px layout, session reset, no JS errors.');
